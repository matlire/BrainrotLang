#include "backend/emitters/runtime/runtime.h"

static void emit_runtime_putchar_(backend_t* be)
{
    be_emitf(be,
        "__brl_putchar:\n"
        "    mov  [__brl_ch], dil\n"
        "    mov  rax, 1\n"
        "    mov  rdi, 1\n"
        "    lea  rsi, [__brl_ch]\n"
        "    mov  rdx, 1\n"
        "    syscall\n"
        "    xor  eax, eax\n"
        "    ret\n\n");
}

static void emit_runtime_getchar_(backend_t* be)
{
    be_emitf(be,
        "__brl_getchar:\n"
        "    cmp  byte [__brl_has_unget], 0\n"
        "    je   .L_getchar_read\n"
        "    mov  byte [__brl_has_unget], 0\n"
        "    movzx rax, byte [__brl_unget_ch]\n"
        "    ret\n"
        ".L_getchar_read:\n"
        "    mov  rax, 0\n"
        "    mov  rdi, 0\n"
        "    lea  rsi, [__brl_ch]\n"
        "    mov  rdx, 1\n"
        "    syscall\n"
        "    cmp  rax, 1\n"
        "    jne  .L_getchar_eof\n"
        "    movzx rax, byte [__brl_ch]\n"
        "    ret\n"
        ".L_getchar_eof:\n"
        "    mov  rax, -1\n"
        "    ret\n\n");
}

static void emit_runtime_ungetchar_(backend_t* be)
{
    be_emitf(be,
        "__brl_ungetchar:\n"
        "    cmp  rdi, 0\n"
        "    jl   .L_unget_ret\n"
        "    mov  [__brl_unget_ch], dil\n"
        "    mov  byte [__brl_has_unget], 1\n"
        ".L_unget_ret:\n"
        "    ret\n\n");
}

static void emit_runtime_print_i64_(backend_t* be)
{
    be_emitf(be,
        "__brl_print_i64:\n"
        "    push rbx\n"
        "    push r12\n"
        "    lea  rsi, [__brl_outbuf + 127]\n"
        "    mov  byte [rsi], 10\n"
        "    mov  rax, rdi\n"
        "    xor  r12d, r12d\n"
        "    cmp  rax, 0\n"
        "    jge  .L_pi_abs\n"
        "    mov  r12d, 1\n"
        "    neg  rax\n"
        ".L_pi_abs:\n"
        "    mov  rbx, 10\n"
        "    cmp  rax, 0\n"
        "    jne  .L_pi_loop\n"
        "    dec  rsi\n"
        "    mov  byte [rsi], '0'\n"
        "    jmp  .L_pi_sign\n"
        ".L_pi_loop:\n"
        "    xor  rdx, rdx\n"
        "    div  rbx\n"
        "    add  dl, '0'\n"
        "    dec  rsi\n"
        "    mov  [rsi], dl\n"
        "    test rax, rax\n"
        "    jne  .L_pi_loop\n"
        ".L_pi_sign:\n"
        "    test r12d, r12d\n"
        "    jz   .L_pi_write\n"
        "    dec  rsi\n"
        "    mov  byte [rsi], '-'\n"
        ".L_pi_write:\n"
        "    lea  rdx, [__brl_outbuf + 128]\n"
        "    sub  rdx, rsi\n"
        "    mov  rax, 1\n"
        "    mov  rdi, 1\n"
        "    syscall\n"
        "    pop  r12\n"
        "    pop  rbx\n"
        "    xor  eax, eax\n"
        "    ret\n\n");
}

